#!/usr/bin/env node
/*
 * Generates the mobile-sized copies of every large photograph and the manifest
 * that tells the components which copies exist.
 *
 * Why not at build time: GitHub's runner would then need a WebP encoder on every
 * deploy, and a build that silently skipped a variant would ship a srcset
 * pointing at a 404. The copies are committed instead, so the build stays a
 * pure Vite build and the manifest is a plain file that can be diffed.
 *
 * Run it after adding or replacing a photo:
 *
 *   node tools/gen-responsive-images.mjs
 *
 * Existing variants are left alone unless the original is newer, so the second
 * run costs nothing.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const IMG_DIR = join(root, 'public/assets/images');
const MANIFEST = join(root, 'src/lib/imageVariants.js');

/* Two tiers, chosen from what a phone actually asks for. A 390 pt screen with
 * a 92vw card wants 718 device pixels at dpr 2, so 700 alone would be rejected
 * in favour of a 1.6x-too-wide file; 900 lands just above the request. The
 * original stays in the srcset for desktop and high-dpr phones. */
const WIDTHS = [700, 900];
const MIN_SOURCE_WIDTH = 1100;

function dimensions(file) {
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], {
    encoding: 'utf8',
  });
  const w = Number((out.match(/pixelWidth:\s*(\d+)/) || [])[1]);
  const h = Number((out.match(/pixelHeight:\s*(\d+)/) || [])[1]);
  return { w, h };
}

function encode(file, out, width) {
  execFileSync('ffmpeg', [
    '-hide_banner',
    '-loglevel', 'error',
    '-y',
    '-i', file,
    '-vf', `scale=${width}:-2`,
    '-c:v', 'libwebp',
    '-quality', '80',
    '-compression_level', '6',
    out,
  ]);
}

const files = readdirSync(IMG_DIR)
  .filter((f) => f.endsWith('.webp'))
  // Sized copies of a sized copy is how a folder ends up with three of
  // everything; only the originals are sources.
  .filter((f) => !/-\d+w\.webp$/.test(f))
  .sort();

const manifest = {};
let made = 0;
let skipped = 0;

for (const name of files) {
  const file = join(IMG_DIR, name);
  const { w } = dimensions(file);
  if (!w || w < MIN_SOURCE_WIDTH) continue;

  const variants = [];
  for (const width of WIDTHS) {
    if (width >= w) continue;
    const outName = `${basename(name, '.webp')}-${width}w.webp`;
    const out = join(IMG_DIR, outName);
    const fresh = existsSync(out) && statSync(out).mtimeMs >= statSync(file).mtimeMs;
    if (!fresh) {
      encode(file, out, width);
      made += 1;
    } else {
      skipped += 1;
    }
    variants.push([`/assets/images/${outName}`, width]);
  }
  if (variants.length) manifest[`/assets/images/${name}`] = variants;
}

const body = `/*
 * Responsive variants, generated by tools/gen-responsive-images.mjs — do not edit
 * by hand. Each entry lists the smaller copies that exist for an original, so a
 * srcset is only ever built from files that are really on disk.
 */
export const VARIANTS = ${JSON.stringify(manifest, null, 2)};

/* Widest copy first, so a browser that ignores srcset order still ends up with
 * something sensible. The original is appended by imgAttrs() from imageSize.js,
 * which is where the true width lives. */
export function variantSet(src) {
  const list = VARIANTS[src];
  if (!list || !list.length) return null;
  return list.map(([url, width]) => \`\${url} \${width}w\`).join(', ');
}
`;

writeFileSync(MANIFEST, body);
console.log(
  `variants: ${made} written, ${skipped} already current, ${Object.keys(manifest).length} sources listed`
);
